    /// Whether `s` is a 64-character lowercase-hex string — the shape of an
    /// `argv_sha256` fingerprint.
    fn is_sha256_hex(s: Option<&str>) -> bool {
        matches!(s, Some(s) if s.len() == 64 && s.bytes().all(|b| matches!(b, b'0'..=b'9' | b'a'..=b'f')))
    }

