//! The versioned JSONL lifecycle-event schema and its emitter.
//!
//! This module owns processkit-cli's **normative event contract** (`AGENTS.md`,
//! "This repository owns the normative JSONL schema"): every event is one JSON
//! object on its own line, carrying a `schema_version`, written only to the
//! `--jsonl` file — never to stdout, so the child's stream stays pristine
//! (`AGENTS.md`, "Streams are strictly separated"). Adapters (processkit-py's
//! CLI) pin `schema_version` and reimplement these shapes, so the field set here
//! is a public API: `docs/schema.md` is the human-readable normative document and
//! `fixtures/schema/v1/events.jsonl` is the golden material adapters test against
//! (regenerated by [`tests::golden_stream_matches_the_fixture`]).
//!
//! Three field groups are shaped to keep the wire form stable as capabilities grow:
//!
//! - **Enriched member fields.** Beyond the bare PID, [`Member`] carries `ppid`,
//!   executable `name`, and `start_time`, filled from ProcessKit's
//!   `ProcessGroup::members_info()` (`AGENTS.md`, "Build strictly on the public
//!   `processkit` API") rather than a local process-enumeration path. Each field
//!   stays declared `Option`: `members_info()` itself reports an enriching field
//!   `None` wherever the platform can't read it (the "bare" BSDs report none of
//!   them) or a member vanished between enumeration and metadata read, so a
//!   `null` here is an honest per-field/per-platform gap, never a placeholder for
//!   unimplemented enrichment (`docs/schema.md`, "Enriched member fields").
//!   `start_time` is `members_info()`'s opaque, platform-specific start-time
//!   *token* — not a wall-clock timestamp, and not comparable across platforms
//!   (see [`processkit::MemberInfo::start_time`]) — carried here as its decimal
//!   string rather than a number, so the wire shape never implies it is safe to
//!   treat as an epoch time or to do arithmetic on.
//! - **Command line / argv redaction (shipped in T-005).** Command lines carry
//!   secrets, so argv is redacted by default (`AGENTS.md`, "Argv is redacted by
//!   default"): a redacted `command` omits the raw `argv` and instead carries a
//!   one-way SHA-256 fingerprint of argv (`argv_sha256`) plus, for recognized
//!   worker shapes, a categorical `hint` (see [`HINT_RULES`]). Neither can reveal
//!   the command line, so both are filled on **every** run; `--argv-raw` only adds
//!   the raw `argv` array on top. Populating these once-reserved fields does not
//!   change the event's wire shape. Both are derived from argv's *canonical bytes*
//!   (see [`CommandInfo`] and [`canonical_argv_bytes`]) rather than a lossy Unicode
//!   rendering, so an argument the local platform allows but Unicode cannot express
//!   keeps its own identity instead of collapsing onto every other such argument.
//! - **Whole-tree resource measurements (shipped in T-317).**
//!   [`Event::ResourceSummary`]'s five measurements are each declared `Option` for the
//!   same reason as the enriched member fields above: the containment mechanism, not
//!   this crate, decides which counters exist — and, on Linux, whether they survive to
//!   the read point — so a `null` is an honest per-axis gap and never a placeholder or a
//!   stand-in `0`. This group adds one qualifier the other two do not need —
//!   `read_error` — because here an all-`null` payload is *also* a legitimate successful
//!   reading (a mechanism that keeps no whole-tree accounting at all, or a Linux cgroup
//!   v2 read after the tree has exited), so the values alone cannot distinguish a gap
//!   from a failed read. See that variant's own docs and `docs/resource-limits.md`, "What
//!   the tree consumed", for the normative platform matrix.

use std::io::Write;
use std::path::Path;
use std::time::{Duration, SystemTime};

use serde::{Deserialize, Serialize};

use processkit::{Command as PkCommand, Mechanism, MemberInfo, Outcome, ParentDeathCleanup};

/// The schema version stamped on every event. Part of the compatibility surface:
/// any breaking change to an event's shape is a **major** bump of this number
/// (`docs/schema.md`, "Versioning").
pub const SCHEMA_VERSION: u32 = 1;

/// Structured observations from ProcessKit's graceful-stop driver. Present only
/// when the runner attempted soft-stop -> grace -> escalation; natural exits and
/// immediate control-plane kills carry `null` instead.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct ShutdownInfo {
    /// ProcessKit's pre-attempt capability probe: `whole_tree`, `opt_in_members`,
    /// or `none`.
    pub soft_stop_scope: &'static str,
    /// What the stop driver observed: `sent`, `unsupported`, or `failed`.
    pub soft_signal: &'static str,
    /// Reported member counts; `null` means ProcessKit could not read the set.
    pub members_before: Option<usize>,
    pub members_after: Option<usize>,
    /// Report-only facts are `null` if the stop operation itself failed before it
    /// could return a `ShutdownReport`.
    pub drained_within_grace: Option<bool>,
    pub escalated: Option<bool>,
    pub elapsed_ms: Option<u64>,
}

/// The wire record actually serialized per line: the common envelope
/// (`schema_version`, `time`) plus the flattened event body (its `event` type tag
/// and payload). Field order here is the on-the-wire order and is stable.
#[derive(Serialize)]
struct Record<'a> {
    schema_version: u32,
    /// Emission time, RFC 3339 UTC with millisecond precision. For `root_exited`
    /// this doubles as the required exit timestamp — the moment the runner
    /// observed the child leave.
    time: String,
    #[serde(flatten)]
    event: &'a Event,
}

/// One lifecycle event. Internally tagged (`"event": "<snake_case>"`) so each line
/// is self-describing; every variant is documented in `docs/schema.md`.
#[derive(Debug, Serialize)]
#[serde(tag = "event", rename_all = "snake_case")]
pub enum Event {
    /// The run has started: the child is spawned into the container and its root
    /// PID, the containment mechanism, the working directory, and the (redacted)
    /// command are known.
    RunStarted {
        run_id: String,
        /// Operator-provided run labels, sorted by key for deterministic JSON.
        labels: std::collections::BTreeMap<String, String>,
        /// The root child's PID. `null` if the backend did not expose one.
        root_pid: Option<u32>,
        /// `job_object` | `cgroup_v2` | `process_group` | `process_reaper` |
        /// `unknown` (see [`mechanism_str`]).
        mechanism: &'static str,
        /// `whole_tree` | `direct_child_only` | `none`: the cleanup guarantee that
        /// remains if the runner itself dies without running destructors.
        abrupt_cleanup: &'static str,
        /// Absolute working directory the child runs in, or `null` if it could not
        /// be resolved.
        cwd: Option<String>,
        command: CommandInfo,
    },
    /// A point-in-time snapshot of the container's members, including the enriched
    /// per-member fields ProcessKit's `members_info()` reports (see module docs
    /// and [`Member`]).
    ///
    /// `reason` names what asked for this particular snapshot: `spawn` for the one
    /// every run emits right after the child is spawned, `interval` for a periodic
    /// re-sample under `run --snapshot-interval`. It is always present — a run
    /// without the flag emits exactly the one `spawn` snapshot it always did, now
    /// self-describing — and it is deliberately the *only* thing that distinguishes
    /// the two on a successful read: both are produced by the same
    /// `emit_members_snapshot` through the same `members_info()` enrichment, so the
    /// shapes cannot drift (`docs/schema.md`, "members_snapshot").
    ///
    /// `read_error` is `true` when the member read itself failed — in that case
    /// `members` is an empty fallback rather than an observation, exactly as
    /// `cleanup_started`'s `members_before` `0` and `cleanup_finished`'s empty
    /// `remaining_pids` are under their own `read_error` flags. The event is emitted
    /// either way, so a failed sample is recorded **in the stream** instead of being
    /// silently dropped (see `src/run/mod.rs`, `SnapshotReason`, for why that
    /// matters most in a detached run, whose stderr is `null`).
    MembersSnapshot {
        /// `spawn` (once, right after the child is spawned) or `interval` (a
        /// `--snapshot-interval` re-sample). First on the wire so the discriminator
        /// stays readable ahead of the potentially long `members` array.
        reason: &'static str,
        /// `true` when `members_info()` failed: `members` is then the empty
        /// fallback, not a confirmed-empty tree. Ahead of `members` for the same
        /// readability reason as `reason`.
        read_error: bool,
        members: Vec<Member>,
    },
    /// The root child exited on its own. `code` is set for a normal exit; `signal`
    /// for a Unix signal death; both `null` only for an outcome without either.
    RootExited {
        /// `exited` | `signalled` | `timed_out` | `unknown` (see [`outcome_fields`]).
        outcome: &'static str,
        code: Option<i32>,
        signal: Option<i32>,
    },
    /// Container teardown is beginning; `members_before` is the tree size about to
    /// be reaped. `read_error` is `true` when the pre-cleanup member read itself
    /// failed — in that case `members_before` is the same `0` fallback the field
    /// always carried on a read failure, but no longer stands unqualified as a
    /// confirmed empty tree; a consumer must check this flag before trusting a `0`
    /// as an observation rather than a gap (`docs/schema.md`, "cleanup_started").
    /// Always present and `false` on every successful read — the additive flag
    /// this event gained alongside `output_captured`'s `write_error` — so the
    /// success-path payload is otherwise unchanged.
    CleanupStarted {
        members_before: usize,
        read_error: bool,
    },
    /// Container teardown finished. `remaining_pids` is a post-hard-kill snapshot
    /// (empty on the Job Object / cgroup mechanisms; on the POSIX process-group
    /// fallback an unreaped just-exited child may still be listed as a member —
    /// see [`ProcessGroup::members`](processkit::ProcessGroup::members)).
    /// `soft_terminate` describes the soft-stop tier for a runner-imposed ending
    /// (`signalled` | `unsupported` | `failed`), and is `null` on the natural-exit
    /// path where no soft stop is attempted. `read_error` is `true` when the
    /// post-kill member read itself failed — in that case `remaining`/
    /// `remaining_pids` fall back to the same empty snapshot as before, but no
    /// longer stand unqualified as a confirmed-clean teardown (mirrors
    /// `cleanup_started`'s flag; `docs/schema.md`, "cleanup_finished").
    /// `kill_error` independently records that `ProcessGroup::kill_all()` returned
    /// an error. In that case even a successful, empty post-kill member read is not
    /// proof of a clean teardown: the tree may have drained while the container
    /// itself remained in an unclean state (for example, ProcessKit's refused-thaw
    /// failure). A confirmed-clean result therefore requires both flags to be
    /// `false` and `remaining` to be `0`.
    CleanupFinished {
        remaining: usize,
        remaining_pids: Vec<u32>,
        soft_terminate: Option<&'static str>,
        shutdown: Option<ShutdownInfo>,
        read_error: bool,
        kill_error: bool,
    },
    /// A configured ProcessKit resource limit could not be applied. Emitted when a
    /// `run` given `--max-memory`/`--max-processes`/`--cpu-quota` asks for a cap the
    /// active mechanism cannot honor: it fires **pre-spawn** (the child never
    /// started) and covers only the *"could not be applied"* branch of this event's
    /// contract — a whole-tree container that is `Unsupported` (FreeBSD's process
    /// reaper, macOS/other BSDs, the Linux
    /// process-group fallback) or `Unenforceable` (a Linux cgroup v2 whose
    /// controllers can't be enabled). It precedes the same `container_failed{create}`
    /// → `runner_exit` tail every group-creation failure takes (see `src/run/launch.rs`,
    /// `create_group`, and `docs/schema.md`, "limit_hit"). Nonsensical values
    /// (`--max-memory 0`, a non-positive `--cpu-quota`) are rejected earlier as a
    /// `USAGE` form error, so this event never carries ProcessKit's `Invalid` reason.
    /// Because this failure happens before a `ProcessGroup` exists, it has no
    /// accompanying `limit_evidence` event.
    LimitHit {
        /// Which limit could not be applied: `memory` / `processes` / `cpu`.
        limit: String,
        detail: Option<String>,
    },
    /// Post-run evidence for a run whose requested cap was installed in a
    /// successfully created `ProcessGroup`.
    /// Each axis keeps ProcessKit's three-valued verdict: `tripped` means the
    /// kernel recorded the cap engaging, `not_tripped` means authoritative
    /// evidence recorded no engagement (or no cap was requested on that axis),
    /// and `unknown` means the active mechanism cannot provide evidence. This
    /// is deliberately a separate event so the pre-spawn `limit_hit` payload
    /// and meaning remain unchanged.
    LimitEvidence {
        /// Memory-cap verdict: `tripped`, `not_tripped`, or `unknown`.
        memory: &'static str,
        /// Process-count-cap verdict: `tripped`, `not_tripped`, or `unknown`.
        processes: &'static str,
        /// CPU-quota verdict: `tripped`, `not_tripped`, or `unknown`.
        cpu: &'static str,
    },
    /// What the contained tree actually consumed: one `ProcessGroup::stats()` reading of
    /// whatever the active mechanism accounts for, taken after the ending is decided and
    /// before teardown consumes the group — the same read point as
    /// [`Event::LimitEvidence`], for the same reason: what it reads lives in the
    /// container, so it is gone once the container is.
    ///
    /// **The read point is part of the contract, not an implementation detail.** A
    /// Windows Job Object's accounting block outlives the processes charged to it, so
    /// its figures cover the whole job whatever the ending; a Linux cgroup v2 sums
    /// memory and CPU out of `/proc` over the members live *at that instant*, so on the
    /// natural-exit path — where the child has already exited and been reaped — those
    /// two axes are `null` there, and only a runner-imposed ending (read before the soft
    /// stop) populates them. See `docs/resource-limits.md`, "What the tree consumed",
    /// consequence 5; that matrix, not this event's field list, is the authority on
    /// which axis carries a number where.
    ///
    /// **Emitted on every run that spawned the child**, cap or no cap, on every
    /// platform — unlike `limit_evidence`, which only answers a question a `--max-*`
    /// flag asked. It is one synchronous read of accumulators the kernel already
    /// keeps, not a sample, so there is nothing for an opt-in flag to save (see
    /// `docs/schema.md`, "resource_summary", for the recorded "always, not on a flag"
    /// decision and its cost).
    ///
    /// **Every measurement is independently nullable, and `null` always means *this
    /// mechanism, at this read point, does not account for it*** — never "zero", and
    /// never a value this runner improved by taking a maximum over its own periodic
    /// reads (that would describe when we looked, not what the tree did). Per the
    /// normative matrix: `peak_process_count` is always `null` on Windows, the IO byte
    /// counters are always `null` on FreeBSD, macOS/other BSDs, and the POSIX fallback and need Linux
    /// cgroup v2's `io` controller enabled, memory and CPU are `null` on a Linux cgroup
    /// v2 natural exit as described above, and neither IO counter is comparable *across*
    /// platforms (a Job Object counts all read/write traffic; cgroup `io.stat` counts
    /// only what crossed the block layer).
    ///
    /// `read_error` is `true` when `stats()` itself failed; every measurement is then
    /// `null` and the event is emitted anyway, rather than skipped. That flag is not
    /// ceremony here — it is the **only** thing that separates a failed read from a
    /// legitimate all-`null` success, which is what a POSIX-fallback run reports by
    /// design and what a flagless Linux cgroup v2 run reports on a natural exit. Without
    /// it the two would be indistinguishable on the wire (the same honest-degradation
    /// contract as `members_snapshot`'s `read_error`, where an empty `members` array is
    /// likewise ambiguous without the flag).
    ResourceSummary {
        /// `true` when the `stats()` read failed: every measurement below is then
        /// `null` as a gap, not as a platform's confirmed "not accounted". First on
        /// the wire so the qualifier is read before the numbers it qualifies.
        read_error: bool,
        /// Peak memory the whole tree used, bytes; `null` where the mechanism keeps no
        /// accumulator this read can reach. Platform-specific in meaning and **not**
        /// comparable across platforms — a Windows Job Object reports peak *committed*
        /// memory (`PeakJobMemoryUsed`), a Linux cgroup v2 the sum of the peak resident
        /// sets of the members live *at the read point*, which is why it is `null` after
        /// a natural exit.
        peak_memory_bytes: Option<u64>,
        /// Total CPU time (user + kernel) the tree accumulated, **milliseconds** —
        /// the unit every other duration in this schema uses (`elapsed_ms`,
        /// `timeout_ms`, `grace_ms`), which is why this one field is renamed from
        /// ProcessKit's `total_cpu_time` rather than carrying an opaque `Duration`.
        /// Truncated toward zero, so a run that used less than a millisecond of CPU
        /// reports a **measured** `0`; `null` is the only value that means unknown.
        /// Windows counts every process ever in the job; a Linux cgroup v2 only the
        /// members live at the read point, so it too is `null` after a natural exit.
        total_cpu_ms: Option<u64>,
        /// Bytes the tree read, `null` where the mechanism does not account for IO.
        io_read_bytes: Option<u64>,
        /// Bytes the tree wrote, `null` where the mechanism does not account for IO.
        /// On Linux this is block-layer writeback, which can land after the member
        /// that dirtied the page exited — or not at all if the group is torn down
        /// first — so a short write-and-exit run may report fewer bytes than it
        /// handed to `write(2)`.
        io_write_bytes: Option<u64>,
        /// High-water mark of how many processes the tree held **at once**; `null`
        /// where the mechanism keeps no such counter, which includes **all** of
        /// Windows (a Job Object tracks only "now" and "ever assigned", neither of
        /// which is a peak). On Linux it is the `pids` controller's `pids.peak`,
        /// which charges every *task*, so it equals a process count only while every
        /// member is single-threaded.
        peak_process_count: Option<u64>,
    },
    /// A runner deadline elapsed while the child was still running: either the
    /// whole-run `--timeout`, or the `--idle-timeout` (the child produced no output
    /// for the idle window). Both share this event, the reserved `TIMEOUT` (106)
    /// terminal code, and the soft-stop → grace → hard-kill teardown described by the
    /// following cleanup events; the always-present `reason` field tells them apart —
    /// `overall` for `--timeout`, `idle` for `--idle-timeout`. `timeout_ms` is the
    /// deadline that actually elapsed (the whole-run window for `overall`, the idle
    /// window for `idle`).
    Timeout {
        timeout_ms: u64,
        grace_ms: Option<u64>,
        /// Which deadline fired: `overall` (`--timeout`) or `idle` (`--idle-timeout`).
        reason: &'static str,
    },
    /// A capture stream exceeded its configured per-stream byte ceiling while
    /// `--capture-overflow cancel` was active. This is emitted before the shared
    /// graceful cleanup tail; the terminal runner code is `OUTPUT_OVERFLOW` (113).
    OutputOverflow {
        /// `stdout` or `stderr`: whichever stream crossed its ceiling first.
        stream: &'static str,
        max_bytes: u64,
        grace_ms: Option<u64>,
    },
    /// The run was cancelled and torn down through the shared soft-stop → grace →
    /// hard-kill path. `source` names the trigger: `ctrl_c` for a local `Ctrl-C`,
    /// `sigterm` / `sighup` for the Unix stop signals the runner catches (`kill`,
    /// `systemctl stop`, a cancelled CI job; a hung-up controlling terminal),
    /// `ctrl_break` / `ctrl_close` / `ctrl_logoff` / `ctrl_shutdown` for the Windows
    /// console-control events the runner catches (a `Ctrl-Break`, the console window
    /// closing, a logoff, or a system shutdown), or `control_cancel` for a `cancel`
    /// command that reached the live runner over its control plane (`docs/schema.md`,
    /// "cancelled"). They all share this event because they share the teardown; the
    /// `source` tells them apart (and the terminal `runner_exit` carries the matching
    /// reserved code — `CANCELLED` for every local signal, `CONTROL_CANCELLED` for the
    /// control-plane command).
    Cancelled {
        source: &'static str,
        grace_ms: Option<u64>,
    },
    /// The run was killed by a control-plane `kill` command: an **immediate** hard
    /// kill of the whole tree with no soft stop and no grace (unlike `cancelled`,
    /// which waits out grace first). `source` is `control_kill`. The teardown it
    /// triggers is described by the following `cleanup_started` / `cleanup_finished`
    /// events; the run's terminal code is the reserved `CONTROL_KILLED` (109). There
    /// is no `grace_ms` field — a kill never waits.
    Killed { source: &'static str },
    /// The program could not be started (not found / not executable / bad cwd):
    /// the child never ran. `code` is the runner-band exit code (`SPAWN`).
    SpawnFailed { code: u8, message: String },
    /// Creating the container, joining the child to it, or handing the terminal to
    /// an interactive child failed. `phase` is `create` (the group could not be
    /// created), `attach` (the launch into the group failed for a non-spawn reason),
    /// or `foreground` (the interactive terminal-foreground handoff failed after the
    /// child had already spawned). `code` is the runner-band exit code (`BACKEND`).
    ContainerFailed {
        phase: &'static str,
        code: u8,
        message: String,
    },
    /// The terminal event of every run: the exact code the runner process returns.
    /// Always emitted — including on the runner's own failure — so a child's code
    /// is never lost or aliased (`AGENTS.md`, "Exit-code fidelity"). `source`
    /// names why the runner exited (`child_exit` | `timeout` | `output_overflow` | `cancelled` |
    /// `control_cancel` | `control_kill` | `spawn_error` | `container_error` |
    /// `internal` | `setup`); `child_code` carries the child's own code when it
    /// exited on its own, and is `null` for a runner-imposed ending or a child
    /// that never produced one.
    RunnerExit {
        code: i32,
        source: &'static str,
        child_code: Option<i32>,
    },
    /// Bounded stdout/stderr capture (`--capture-dir`) finished: for each stream,
    /// the file it was written to, the full byte counter, the SHA-256 of the
    /// captured bytes, an explicit truncation flag, and an explicit write-error flag
    /// (see [`CaptureInfo`] and `docs/schema.md`, "output_captured"). Emitted **only**
    /// when `--capture-dir`
    /// is set — a run without capture is byte-for-byte unchanged — once per run,
    /// after the teardown pair and before `runner_exit`.
    OutputCaptured {
        stdout: CaptureInfo,
        stderr: CaptureInfo,
    },
}

/// One entry of a [`Event::MembersSnapshot`]: a PID plus the enriched fields
/// (`ppid`, executable `name`, `start_time`) [`Member::from_info`] fills from
/// ProcessKit's `members_info()` (module docs, "Enriched member fields"). Each
/// enriched field is independently `Option` and `None` wherever the platform (or
/// a process that vanished mid-read) could not report it — never a fabricated
/// value.
///
/// `Deserialize` as well as `Serialize`: the same member shape is reused by the
/// control-plane `inspect` snapshot ([`crate::control::Snapshot`]), whose client
/// parses the response back — so the two "container member" views never drift.
#[derive(Debug, Serialize, Deserialize)]
pub struct Member {
    pub pid: u32,
    pub ppid: Option<u32>,
    pub name: Option<String>,
    pub start_time: Option<String>,
}

impl Member {
    /// A member built from a bare PID: every enriched field is explicitly absent.
    /// Used where only a PID is known (hand-built test/fixture data); production
    /// snapshotting goes through [`Member::from_info`].
    pub fn from_pid(pid: u32) -> Self {
        Self {
            pid,
            ppid: None,
            name: None,
            start_time: None,
        }
    }

    /// A member built from ProcessKit's enriched [`MemberInfo`]
    /// (`ProcessGroup::members_info()`): `ppid` and the executable `name` carry
    /// over directly (each already `None` wherever the platform can't report it —
    /// see [`MemberInfo`]'s per-field platform matrix); `start_time` is
    /// `members_info()`'s opaque, platform-specific start-time *token* — not a
    /// wall-clock timestamp, not comparable across platforms — rendered as its
    /// decimal string, matching the schema's `string, nullable` type for exactly
    /// that reason (`docs/schema.md`, "Enriched member fields").
    pub fn from_info(info: MemberInfo) -> Self {
        Self {
            pid: info.pid(),
            ppid: info.ppid(),
            name: info.exe_name().map(str::to_string),
            start_time: info.start_time().map(|token| token.to_string()),
        }
    }
}

/// One stream's bounded-capture result, as carried by [`Event::OutputCaptured`].
///
/// `bytes` is the **full** byte counter — every decoded byte the stream produced,
/// so it exceeds the file's size once the stream was truncated or a write failed.
/// `sha256` is the lowercase-hex digest of the bytes actually written to `path` (so
/// a consumer can verify the file it holds), computed with the same [`crate::hash`]
/// primitive as the argv fingerprint. `truncated` and `write_error` are two
/// **explicit** flags, never inferred from the file's size, that between them tell a
/// consumer whether the file is the whole stream: `truncated` is set when the stream
/// outran the per-stream capture ceiling and the tail was deliberately dropped;
/// `write_error` is set when a file write failed mid-stream (a disk problem), after
/// which capture stopped touching the broken file. The two are independent — a stream
/// can be both — so "captured in full" is `!truncated && !write_error`, and each
/// incomplete cause is distinguishable from the other on the flags alone
/// (`docs/schema.md`, "output_captured").
#[derive(Debug, Serialize)]
pub struct CaptureInfo {
    path: String,
    bytes: u64,
    sha256: String,
    truncated: bool,
    write_error: bool,
}

impl CaptureInfo {
    /// Assemble one stream's capture metadata for the event.
    pub fn new(
        path: String,
        bytes: u64,
        sha256: String,
        truncated: bool,
        write_error: bool,
    ) -> Self {
        Self {
            path,
            bytes,
            sha256,
            truncated,
            write_error,
        }
    }

    /// The full byte counter (every produced byte, past the ceiling too).
    #[cfg(test)]
    pub fn bytes(&self) -> u64 {
        self.bytes
    }

    /// The lowercase-hex SHA-256 of the captured (written) bytes.
    #[cfg(test)]
    pub fn sha256(&self) -> &str {
        &self.sha256
    }

    /// Whether the stream outran the capture ceiling.
    #[cfg(test)]
    pub fn truncated(&self) -> bool {
        self.truncated
    }

    /// Whether a file write failed mid-stream, leaving the on-disk transcript short
    /// of the byte counter.
    #[cfg(test)]
    pub fn write_error(&self) -> bool {
        self.write_error
    }
}

/// The command a run executed, in its redaction-aware v1 shape. `redacted` is
/// `true` by default and `false` only under `--argv-raw`; `argv` carries the raw
/// argv strings only when not redacted. `argv_sha256` (a one-way fingerprint) and
/// `hint` (a worker-shape category, or `null` when unrecognized) are filled on
/// every run — they never expose the command line — so redaction never blinds a
/// consumer to *which* run it is looking at (see [`argv_sha256_hex`],
/// [`classify_hint`], and `docs/schema.md`, "Command redaction").
///
/// # Argv that is not valid Unicode
///
/// An argv element is an *OS string*, not a Unicode string: on Unix it is an
/// arbitrary NUL-free byte sequence, and on Windows an arbitrary sequence of
/// UTF-16 code units that may contain unpaired surrogates. Neither is
/// representable in JSON verbatim, and this type used to resolve that by rendering
/// every element with `to_string_lossy()` *before* both the recorded `argv` and
/// the fingerprint were derived — replacing each ill-formed sequence with U+FFFD.
/// That silently destroyed identity: the Unix argvs `[b"\xff"]` and `[b"\xfe"]`
/// both became `"\u{fffd}"`, so two genuinely different live commands shared one
/// `argv_sha256` in the JSONL stream and in the registry (`list`/`inspect`)
/// diagnostics, and `--argv-raw` handed back a reconstruction rather than the raw
/// argv it promises.
///
/// Both fields are now derived from one [`RenderedArgv`] — each element's exact
/// canonical bytes — and differ only in how those bytes reach the wire:
///
/// - `argv_sha256` hashes the canonical bytes themselves (see
///   [`argv_sha256_hex`]), so two distinct argvs cannot collide into one
///   fingerprint.
/// - `argv` records each element through [`render_element_text`], which is
///   **lossless**: an element that is valid Unicode is the JSON string it always
///   was, and one that is not is written in a reversible, NUL-marked byte escape.
///
/// Of the two admissible answers for the raw field — encode losslessly, or refuse
/// / report the element as unrepresentable — this takes the first, deliberately.
/// `--argv-raw` exists so an operator can see *what actually ran*; refusing would
/// withhold exactly the case where argv is hardest to guess (an argument some
/// upstream tooling mangled) and would make two different mangled argvs
/// indistinguishable a second time, in the very field that opted out of
/// redaction. Encoding also keeps the field's `array of string` type, so no
/// existing v1 consumer's *parse* changes (`docs/schema.md`, "Command redaction").
/// Parsing is not the whole of a consumer's job, though: an escaped element is the
/// only string in this schema that can carry U+0000, so one that stores or forwards
/// the *decoded* value must check that its sink accepts it (see
/// [`ARGV_ESCAPE_MARKER`]). That obligation is documented, not implicit — the same
/// section states it, alongside the fact that the emitted line itself stays NUL-free.
#[derive(Debug, Serialize)]
pub struct CommandInfo {
    redacted: bool,
    argv: Option<Vec<String>>,
    argv_sha256: Option<String>,
    hint: Option<String>,
}

impl CommandInfo {
    /// Build the command field for `argv`. The one-way `argv_sha256` fingerprint
    /// and the worker-shape `hint` are always computed — neither can leak the
    /// command line — so they are present whether or not the raw argv is recorded.
    /// `argv_raw` additionally records the raw argv array (losslessly, see this
    /// type's docs); without it the argv is omitted (redacted) and only the
    /// fingerprint and hint remain.
    pub fn for_argv<I, S>(argv: I, argv_raw: bool) -> Self
    where
        I: IntoIterator<Item = S>,
        S: AsRef<std::ffi::OsStr>,
    {
        // Render argv once — to the canonical bytes the fingerprint hashes and the
        // text form `--argv-raw` records and the classifier inspects — then derive
        // the fingerprint and hint from that single rendering, through the very
        // same [`CommandFingerprint`] the registry record publishes, so the two can
        // never disagree about one run. Only the raw array is gated behind the
        // flag; the redaction-safe fields are computed unconditionally.
        let rendered = RenderedArgv::render(argv);
        let fingerprint = CommandFingerprint::for_rendered_argv(&rendered);
        Self {
            redacted: !argv_raw,
            argv: argv_raw.then(|| rendered.into_text()),
            argv_sha256: Some(fingerprint.argv_sha256),
            hint: fingerprint.hint.map(str::to_string),
        }
    }
}

/// The **redaction-safe** identification of a run's command: the one-way argv
/// fingerprint and the categorical worker-shape hint, and nothing else — never the
/// argv itself, in any form.
///
/// This is the whole of what a consumer may learn about a command without being
/// shown it (`AGENTS.md`, "Argv is redacted by default"), factored out of
/// [`CommandInfo`] so the two places that publish it — the JSONL `run_started`
/// event and the per-user registry record ([`crate::registry::Record`], T-215) —
/// derive it from **one** implementation rather than each growing its own. That
/// matters twice over: a second fingerprint implementation could drift from the
/// canonical encoding `docs/schema.md` pins (making the same run fingerprint
/// differently in two artifacts), and a second classifier could emit a label
/// outside the documented catalog.
///
/// It is also the *only* command-derived value the registry is ever handed: the
/// registry's `register` takes this type, not an argv, so raw argv cannot reach a
/// registry record even by mistake — the redaction guarantee there is structural,
/// not a matter of remembering to redact. `--argv-raw` widens only
/// [`CommandInfo::argv`]; it is not even an input here.
#[derive(Debug, Clone)]
pub struct CommandFingerprint {
    /// The lowercase-hex SHA-256 argv fingerprint (see [`argv_sha256_hex`]).
    /// Always present: it is derived from argv but cannot reveal it.
    pub argv_sha256: String,
    /// The worker-shape category from [`classify_hint`], or `None` when the argv
    /// matches no known shape (the common case). Deliberately `&'static str`, not
    /// `String`: a value here can only ever be one of [`HINT_RULES`]' fixed labels,
    /// so no argv content can reach a consumer through this field even in
    /// principle.
    pub hint: Option<&'static str>,
}

impl CommandFingerprint {
    /// The redaction-safe fingerprint of `argv` — the entry point for a caller
    /// holding the raw argv (`run`, which hands the result to the registry).
    pub fn for_argv<I, S>(argv: I) -> Self
    where
        I: IntoIterator<Item = S>,
        S: AsRef<std::ffi::OsStr>,
    {
        Self::for_rendered_argv(&RenderedArgv::render(argv))
    }

    /// The same fingerprint from an already-rendered argv — how
    /// [`CommandInfo::for_argv`] reuses this without rendering argv twice.
    fn for_rendered_argv(argv: &RenderedArgv) -> Self {
        Self {
            argv_sha256: argv_sha256_hex(&argv.bytes),
            hint: classify_hint(&argv.text),
        }
    }
}

/// A run's argv rendered **once**, in the two forms this module publishes it in —
/// the single point every argv-derived value is taken from, so the fingerprint,
/// the `--argv-raw` array, and the worker-shape classifier can never disagree
/// about the same command (three independent encodings is exactly the drift
/// [`CommandFingerprint`] exists to prevent).
///
/// `bytes` is the identity-bearing form and `text` is its wire rendering; `text`
/// is derived from `bytes`, never independently from the `OsStr`, so the JSON a
/// consumer reads and the digest it joins on describe the same argv by
/// construction.
struct RenderedArgv {
    /// Each element's canonical bytes — [`canonical_argv_bytes`]' exact,
    /// non-lossy encoding of the OS string. What [`argv_sha256_hex`] hashes.
    bytes: Vec<Vec<u8>>,
    /// Each element rendered to the JSON string form ([`render_element_text`]):
    /// the element verbatim when it is valid Unicode, its NUL-marked escape when
    /// it is not. What `--argv-raw` records and [`classify_hint`] reads.
    text: Vec<String>,
}

impl RenderedArgv {
    /// Render `argv` into both forms.
    fn render<I, S>(argv: I) -> Self
    where
        I: IntoIterator<Item = S>,
        S: AsRef<std::ffi::OsStr>,
    {
        let bytes: Vec<Vec<u8>> = argv
            .into_iter()
            .map(|arg| canonical_argv_bytes(arg.as_ref()))
            .collect();
        let text = bytes
            .iter()
            .map(|element| render_element_text(element))
            .collect();
        Self { bytes, text }
    }

    /// Take the wire (JSON) rendering, for the `--argv-raw` array.
    fn into_text(self) -> Vec<String> {
        self.text
    }
}

/// One argv element's **canonical bytes**: the exact, unambiguous encoding of the
/// OS string, chosen per platform so that two different OS strings can never
/// render to the same bytes.
///
/// - **Unix** — the element's own bytes, verbatim
///   (`std::os::unix::ffi::OsStrExt::as_bytes`). A Unix argument is an arbitrary
///   NUL-free byte sequence with no encoding attached; its bytes *are* its
///   identity.
/// - **Windows** — the WTF-8 encoding of the element's UTF-16 code units
///   (`std::os::windows::ffi::OsStrExt::encode_wide`, re-encoded by
///   `wtf8_from_wide`). Windows has no byte view of an `OsStr`, and its argv is
///   a UTF-16 sequence that may contain unpaired surrogates; WTF-8 is the standard
///   generalization of UTF-8 that can carry those, which
///   `std`'s own Windows `OsString` is internally stored in.
///
/// Both branches agree on the case that matters for compatibility: for an element
/// that *is* valid Unicode, the canonical bytes are exactly its UTF-8 bytes on
/// every platform, so this preserves — byte for byte — the fingerprint every run
/// with an ordinary command line produced before non-UTF-8 argv was handled at all
/// (`docs/schema.md`, "Fingerprint"). Only argv that no encoding could have
/// represented faithfully changes.
///
/// There is deliberately no third, portable-fallback branch: this crate already
/// builds only for Unix and Windows (`crate::control`'s transport `imp` module has
/// the same two arms and no other), and a `to_string_lossy()` fallback here would
/// quietly reintroduce the very collision this function exists to close.
///
/// This is the Windows counterpart of the same discipline
/// `crate::win_security::to_wide_path` follows for paths: reach for the OS's own
/// representation, never `to_string_lossy()`.
#[cfg(unix)]
fn canonical_argv_bytes(arg: &std::ffi::OsStr) -> Vec<u8> {
    use std::os::unix::ffi::OsStrExt;
    arg.as_bytes().to_vec()
}

/// Windows arm of [`canonical_argv_bytes`] (documented there).
#[cfg(windows)]
fn canonical_argv_bytes(arg: &std::ffi::OsStr) -> Vec<u8> {
    use std::os::windows::ffi::OsStrExt;
    wtf8_from_wide(arg.encode_wide())
}

/// Encode a Windows UTF-16 (really WTF-16) code-unit sequence as WTF-8.
///
/// A surrogate pair is combined into the supplementary scalar it denotes and
/// encoded as ordinary 4-byte UTF-8; any code unit that is *not* part of a pair —
/// including an unpaired surrogate, which `String` cannot hold and
/// `to_string_lossy()` would replace with U+FFFD — is encoded in place by the same
/// UTF-8 bit layout, giving the 3-byte form WTF-8 reserves for it. A sequence with
/// no unpaired surrogate is therefore byte-identical to its UTF-8 encoding, which
/// is what keeps ordinary Windows argv fingerprinting exactly as it did before.
#[cfg(windows)]
fn wtf8_from_wide<I>(units: I) -> Vec<u8>
where
    I: Iterator<Item = u16>,
{
    let mut out = Vec::new();
    let mut units = units.peekable();
    while let Some(unit) = units.next() {
        // Binding the low half out of the *peeked* value (rather than re-reading
        // it after the test) keeps the pair arithmetic unreachable for any input
        // that is not actually a pair — there is no fallback value to get wrong.
        let code = match (unit, units.peek().copied()) {
            (0xD800..=0xDBFF, Some(low @ 0xDC00..=0xDFFF)) => {
                units.next();
                0x1_0000 + ((u32::from(unit) - 0xD800) << 10) + (u32::from(low) - 0xDC00)
            }
            _ => u32::from(unit),
        };
        push_utf8_code_point(&mut out, code);
    }
    out
}

/// Append one code point to `out` in the UTF-8 bit layout. Accepts the surrogate
/// range too (that is what makes the output WTF-8 rather than strict UTF-8); see
/// `wtf8_from_wide`, its only caller.
#[cfg(windows)]
fn push_utf8_code_point(out: &mut Vec<u8>, code: u32) {
    // Every shifted value below is masked to at most 6 bits before the cast, so no
    // truncation is possible; `code` itself is at most 0x10FFFF.
    #[allow(clippy::cast_possible_truncation)]
    match code {
        0x0000..=0x007F => out.push(code as u8),
        0x0080..=0x07FF => {
            out.extend_from_slice(&[0xC0 | (code >> 6) as u8, 0x80 | (code & 0x3F) as u8])
        }
        0x0800..=0xFFFF => out.extend_from_slice(&[
            0xE0 | (code >> 12) as u8,
            0x80 | ((code >> 6) & 0x3F) as u8,
            0x80 | (code & 0x3F) as u8,
        ]),
        _ => out.extend_from_slice(&[
            0xF0 | (code >> 18) as u8,
            0x80 | ((code >> 12) & 0x3F) as u8,
            0x80 | ((code >> 6) & 0x3F) as u8,
            0x80 | (code & 0x3F) as u8,
        ]),
    }
}

/// The marker that opens the escaped form of an argv element: U+0000, the one
/// character that cannot occur inside a real argv element on any supported
/// platform — the same invariant that lets [`argv_sha256_hex`] join elements with
/// a NUL. An element rendered verbatim can therefore never be mistaken for an
/// escaped one, and vice versa, with no in-band flag or extra field.
///
/// **Why it cannot be a printable character.** A printable marker would be a
/// character a real argument may also start with, so every *verbatim* element
/// beginning with it would have to be escaped too — changing how ordinary command
/// lines are recorded (most visibly a Windows path's `\`) for every reader, to
/// spare the one element shape that is not representable anyway. U+0000 confines
/// the new shape to exactly the arguments that forced it.
///
/// The cost of that choice is real but bounded, and `docs/schema.md` ("Raw argv
/// that is not valid Unicode") states it normatively rather than leaving a reader
/// to discover it: an escaped element is the only string value in the schema that
/// can carry U+0000, so a consumer that decodes the JSON and then hands the value
/// to a sink which forbids NUL (PostgreSQL `jsonb`, a C-string API, some YAML/log
/// transports) must re-render or strip it. The emitted line is unaffected — serde
/// writes U+0000 as the ordinary six-character JSON escape, so the JSONL stays
/// NUL-free text (pinned by `escaped_elements_reach_the_wire_as_an_ascii_escape`).
const ARGV_ESCAPE_MARKER: char = '\0';

/// Render one argv element's canonical bytes to the JSON string `--argv-raw`
/// records — losslessly, in one of two mutually distinguishable forms:
///
/// - **Verbatim** — when the bytes are valid UTF-8 and contain no NUL: the element
///   as-is. This is every ordinary command line, rendered exactly as it always
///   was.
/// - **Escaped** — otherwise: [`ARGV_ESCAPE_MARKER`] (U+0000) followed by the
///   element with `\` written `\\` and every byte that is not part of a
///   well-formed UTF-8 sequence (and any NUL) written `\xNN`, two lowercase hex
///   digits. Nothing else is transformed, so the readable part of a mangled
///   argument stays readable next to the bytes that broke it.
///
/// The escape is total and reversible: a reader that strips the leading U+0000 and
/// then maps `\\` → `\`, `\xNN` → that byte, and everything else to its UTF-8
/// bytes recovers the element's canonical bytes exactly. The grammar is normative
/// and mirrored in `docs/schema.md` ("Raw argv that is not valid Unicode"); the
/// in-tree round-trip
/// test `escaped_elements_decode_back_to_their_exact_bytes` is its executable
/// statement.
///
/// Note that this text form is *not* what the fingerprint hashes — that is the
/// canonical bytes themselves ([`argv_sha256_hex`]) — so the escape can never
/// perturb a digest.
fn render_element_text(bytes: &[u8]) -> String {
    match std::str::from_utf8(bytes) {
        Ok(text) if !text.contains(ARGV_ESCAPE_MARKER) => text.to_owned(),
        _ => escape_element_text(bytes),
    }
}

/// The escaped branch of [`render_element_text`] (grammar documented there).
fn escape_element_text(bytes: &[u8]) -> String {
    let mut out = String::from(ARGV_ESCAPE_MARKER);
    let mut rest = bytes;
    loop {
        match std::str::from_utf8(rest) {
            Ok(text) => {
                push_escaped_run(&mut out, text);
                return out;
            }
            Err(error) => {
                let (valid, invalid) = rest.split_at(error.valid_up_to());
                match std::str::from_utf8(valid) {
                    Ok(text) => push_escaped_run(&mut out, text),
                    // Unreachable by `valid_up_to`'s own contract. Escaping the
                    // prefix byte-wise rather than trusting it keeps even an
                    // impossible case lossless instead of dropping bytes.
                    Err(_) => valid
                        .iter()
                        .for_each(|byte| push_byte_escape(&mut out, *byte)),
                }
                // `error_len() == None` means "unexpected end of input": the rest
                // of the element is a truncated sequence, all of it ill-formed.
                let invalid_len = error.error_len().unwrap_or(invalid.len());
                invalid[..invalid_len]
                    .iter()
                    .for_each(|byte| push_byte_escape(&mut out, *byte));
                rest = &invalid[invalid_len..];
            }
        }
    }
}

/// Append a well-formed run of an escaped element: only `\` (the escape
/// introducer) and NUL (the marker character) are rewritten, so the rest of the
/// argument survives readably.
fn push_escaped_run(out: &mut String, text: &str) {
    for character in text.chars() {
        match character {
            '\\' => out.push_str("\\\\"),
            ARGV_ESCAPE_MARKER => push_byte_escape(out, 0),
            _ => out.push(character),
        }
    }
}

/// Append one byte as `\xNN`, two lowercase hex digits.
fn push_byte_escape(out: &mut String, byte: u8) {
    use std::fmt::Write;
    // Writing to a `String` is infallible; the result is discarded deliberately.
    let _ = write!(out, "\\x{byte:02x}");
}

/// The hex SHA-256 fingerprint of a run's argv: each element's **canonical bytes**
/// (see [`canonical_argv_bytes`] — the platform's own exact encoding, not a lossy
/// Unicode rendering) joined by a single NUL byte — a byte that cannot occur
/// inside a real argv element on any platform, so element boundaries stay
/// unambiguous — then hashed. This canonical encoding is documented in
/// `docs/schema.md` ("Fingerprint") so an adapter that re-emits the schema
/// reproduces the exact digest. The hash is one-way, so it fingerprints a command
/// without disclosing it. The digest itself is [`crate::hash::sha256_hex`], the
/// same primitive the bounded output capture hashes with (`docs/schema.md`,
/// "Fingerprint").
///
/// Generic over the element type only so a test can state an expectation in the
/// obvious `&["abc".to_string()]` form; production callers pass the canonical
/// bytes [`RenderedArgv`] rendered.
fn argv_sha256_hex<E: AsRef<[u8]>>(argv: &[E]) -> String {
    let mut encoded = Vec::new();
    for (index, element) in argv.iter().enumerate() {
        if index > 0 {
            encoded.push(b'\0');
        }
        encoded.extend_from_slice(element.as_ref());
    }
    crate::hash::sha256_hex(&encoded)
}

/// One worker-shape classifier rule: the `hint` it emits and the set of substrings
/// that must **all** be present in a run's argv for it to match.
struct HintRule {
    /// The `hint` value emitted when every marker below is found in the argv.
    hint: &'static str,
    /// Substrings that must all appear (case-insensitively) in the argv. Stored in
    /// their readable, documented form; matching lowercases both sides.
    markers: &'static [&'static str],
}

/// The worker-shape hint catalog: plain, ordered data rather than branch logic, so
/// a new shape is one new entry here — and the same table is mirrored in
/// `docs/schema.md`, keeping the catalog visible outside the code. The first rule
/// whose markers all match wins; an argv matching none yields `null`.
///
/// Seed entry — **MSBuild reusable worker nodes.** A build host keeps long-lived
/// `MSBuild.dll` worker processes around (`/nodemode:1 /nodeReuse:true`); they are
/// a classic "stuck after the build" tree. Tagging the shape lets a consumer (the
/// orchestrator) name such a node without its full, possibly secret-bearing
/// command line.
static HINT_RULES: &[HintRule] = &[HintRule {
    hint: "msbuild_node_reuse",
    markers: &["MSBuild.dll", "/nodemode:1", "/nodeReuse:true"],
}];

/// Every `hint` label this catalog can emit — test-only, and `pub(crate)` only for
/// that, so the catalog itself stays private. It exists so a *consumer* of the
/// labels can assert against the real catalog instead of a hand-copied list: the
/// registry's read-side `hint` validator (T-215, `crate::registry`) must accept
/// every label a runner can actually write, and a new catalog entry that violated
/// that shape would otherwise only surface as a silently dropped field at scan
/// time. The same anti-drift discipline the control-socket naming contract uses
/// (see [K-073]).
#[cfg(test)]
pub(crate) fn hint_labels() -> impl Iterator<Item = &'static str> {
    HINT_RULES.iter().map(|rule| rule.hint)
}

/// Classify a run's argv against [`HINT_RULES`], returning the first matching
/// rule's `hint` or `None` when no shape is recognized (the common case). Matching
/// is a case-insensitive substring test over the space-joined argv, so a marker is
/// found whether it is a whole argument or embedded in one (e.g. a full
/// `…/MSBuild.dll` path). The hint is a fixed category label — never argv content —
/// so emitting it does not weaken redaction.
///
/// The input is the *text* rendering of argv ([`RenderedArgv::text`]), not the
/// canonical bytes the fingerprint hashes, and that is deliberate: this classifier
/// is a heuristic over readable substrings and makes **no identity claim** about a
/// command, so it neither needs nor promises the unambiguity `argv_sha256` does.
/// Two different argvs may legitimately classify alike — that is what a *category*
/// is. Every documented marker is ASCII, so an element that carries bytes no
/// encoding can read still matches on whatever of it remains readable; only the
/// escaped bytes themselves (and a doubled `\`) differ from the raw argument, and
/// no marker spans them.
///
/// `pub` so `benches/hint_classifier_bench.rs` (T-187) can measure the classifier
/// in isolation, without the argv-fingerprint SHA-256 that its only other caller,
/// [`CommandInfo::for_argv`], always computes alongside it — matching the crate's
/// documented "future benchmarks reach internal primitives directly" design
/// (`docs/architecture.md`, "Target structure"). Not a stability signal: this
/// module stays `#[doc(hidden)]` and the library carries no semver guarantee.
pub fn classify_hint(argv: &[String]) -> Option<&'static str> {
    let haystack = argv.join(" ").to_ascii_lowercase();
    HINT_RULES
        .iter()
        .find(|rule| {
            rule.markers
                .iter()
                .all(|marker| haystack.contains(marker.to_ascii_lowercase().as_str()))
        })
        .map(|rule| rule.hint)
}

/// Append-only writer for a run's JSONL event stream.
///
/// Each event is written as one line and **flushed immediately**: the runner
/// forwards a completed child's code via [`std::process::exit`], which skips
/// destructors, so a buffered event (including the terminal `runner_exit`) would
/// be lost without a per-event flush. A write failure after the stream is open is
/// best-effort — it warns once on stderr and drops subsequent events rather than
/// aborting an otherwise-healthy run (the child's exit-code fidelity outranks
/// diagnostics); the fail-closed check is at [`Emitter::create`], before the child
/// is ever spawned.
pub struct Emitter {
    file: std::fs::File,
    poisoned: bool,
}

impl Emitter {
    /// Open (creating or truncating) the JSONL file for this run. Fails if the
    /// path cannot be created — the caller treats that as a runner-own failure and
    /// never spawns the child, so no child code can be lost to a logging setup
    /// error.
    pub fn create(path: &Path) -> std::io::Result<Self> {
        let file = std::fs::File::create(path)?;
        Ok(Self {
            file,
            poisoned: false,
        })
    }

    /// Emit one event, stamped with the current time. Infallible by contract: a
    /// write error is reported once to stderr and then swallowed (see the type
    /// docs), so lifecycle wiring never has to branch on logging failure.
    pub fn emit(&mut self, event: &Event) {
        if self.poisoned {
            return;
        }
        let line = match serialize_record(event, now_rfc3339()) {
            Ok(line) => line,
            Err(err) => {
                // A struct with string keys and no I/O cannot fail to serialize;
                // treat the impossible as best-effort rather than panicking.
                self.poison(format_args!("could not serialize a JSONL event: {err}"));
                return;
            }
        };
        if let Err(err) = self
            .file
            .write_all(line.as_bytes())
            .and_then(|()| self.file.write_all(b"\n"))
            .and_then(|()| self.file.flush())
        {
            self.poison(format_args!("could not write a JSONL event: {err}"));
        }
    }

    /// Warn once, then silence further events. Keeps a broken log from spamming
    /// stderr while still surfacing the first failure honestly.
    fn poison(&mut self, reason: std::fmt::Arguments<'_>) {
        eprintln!("processkit-cli: warning: JSONL event logging disabled: {reason}");
        self.poisoned = true;
    }
}

/// Serialize one enveloped event to a compact single-line JSON string (no trailing
/// newline). Separated from [`Emitter::emit`] so tests can render with a fixed
/// timestamp for the golden fixture.
fn serialize_record(event: &Event, time: String) -> serde_json::Result<String> {
    serde_json::to_string(&Record {
        schema_version: SCHEMA_VERSION,
        time,
        event,
    })
}

/// The run identifier for this run: the explicit `--run-id` when given, otherwise
/// a generated value unique per invocation on this host (`run-<pid>-<unix_nanos>`).
pub fn resolve_run_id(explicit: Option<&str>) -> String {
    match explicit {
        Some(id) => id.to_string(),
        None => {
            let nanos = SystemTime::now()
                .duration_since(SystemTime::UNIX_EPOCH)
                .map(|d| d.as_nanos())
                .unwrap_or(0);
            format!("run-{}-{nanos}", std::process::id())
        }
    }
}

/// The stable schema string for a containment [`Mechanism`]. `Mechanism` is
/// `#[non_exhaustive]`, so an unknown future variant maps to `"unknown"` rather
/// than a guess.
pub fn mechanism_str(mechanism: Mechanism) -> &'static str {
    match mechanism {
        Mechanism::JobObject => "job_object",
        Mechanism::CgroupV2 => "cgroup_v2",
        Mechanism::ProcessGroup => "process_group",
        Mechanism::ProcessReaper => "process_reaper",
        _ => "unknown",
    }
}

/// The containment guarantee that survives an abrupt runner death on this target.
/// This is deliberately OS-derived rather than inferred from [`Mechanism`]: Linux
/// cgroups persist after their creator dies, so the enabled PDEATHSIG still covers
/// only the direct child; a Windows Job handle close reaps the whole tree.
///
/// Sourced from `processkit`'s own honest capability report
/// (`Command::kill_on_parent_death_scope`, shipped in processkit 2.3.2) rather than
/// reimplementing the per-platform `cfg!` derivation here, so this crate and
/// `processkit` cannot drift on the claim. `ParentDeathCleanup` is
/// `#[non_exhaustive]`; an unrecognized future variant maps to `"none"` — the
/// conservative choice, since this string is a reaping *guarantee*, not a mere
/// capability label, and must never overclaim.
pub fn abrupt_cleanup_str() -> &'static str {
    abrupt_cleanup_scope_str(PkCommand::kill_on_parent_death_scope())
}

/// The projection [`abrupt_cleanup_str`] applies to whatever scope this host
/// reports, as a pure function of the scope.
///
/// Split out from its host-reading caller for the same reason `soft_stop_mechanism`
/// in `src/run/teardown.rs` takes an explicit `windows` flag instead of reading
/// `cfg!` itself (K-059): a projection that reads the host inside itself can only
/// ever be exercised for *this* machine's answer, so every other arm — and any
/// arm a future ProcessKit variant would land in — is untestable and unauditable
/// off that platform. As a pure function it can be driven over every variant on
/// any host, which is exactly what the upstream identifier drift gate
/// (`tests/spec_drift.rs`) does: it resolves each identifier in ProcessKit's
/// shipped `spec/identifiers.json` back to its variant and requires this
/// function to render it deliberately rather than fall into the `_` arm.
pub fn abrupt_cleanup_scope_str(scope: ParentDeathCleanup) -> &'static str {
    match scope {
        ParentDeathCleanup::WholeTree => "whole_tree",
        ParentDeathCleanup::DirectChildOnly => "direct_child_only",
        ParentDeathCleanup::Unsupported => "none",
        _ => "none",
    }
}

/// Decompose a completed run's [`Outcome`] into the `root_exited` fields:
/// `(outcome, code, signal)`. `Outcome` is `#[non_exhaustive]`; an unrecognized
/// variant is reported as `"unknown"` with neither a code nor a signal.
pub fn outcome_fields(outcome: &Outcome) -> (&'static str, Option<i32>, Option<i32>) {
    match outcome {
        Outcome::Exited(code) => ("exited", Some(*code), None),
        Outcome::Signalled(Some(signal)) => ("signalled", None, Some(*signal)),
        Outcome::Signalled(None) => ("signalled", None, None),
        Outcome::TimedOut => ("timed_out", None, None),
        _ => ("unknown", None, None),
    }
}

/// The current time formatted for the event envelope.
fn now_rfc3339() -> String {
    format_rfc3339_utc(SystemTime::now())
}

/// Format a [`SystemTime`] as RFC 3339 UTC with millisecond precision
/// (`YYYY-MM-DDTHH:MM:SS.sssZ`). Hand-rolled to avoid a date-library dependency
/// for a single field; the civil-date conversion is Howard Hinnant's standard
/// `civil_from_days` algorithm (validated in [`tests::timestamp_matches_known_vectors`]).
///
/// `pub(crate)` so the run registry ([`crate::registry`]) stamps its record's
/// `started_at` with the same formatter rather than duplicating the civil-date math.
pub(crate) fn format_rfc3339_utc(time: SystemTime) -> String {
    let dur = time
        .duration_since(SystemTime::UNIX_EPOCH)
        .unwrap_or(Duration::ZERO);
    let secs = dur.as_secs() as i64;
    let millis = dur.subsec_millis();

    let days = secs.div_euclid(86_400);
    let secs_of_day = secs.rem_euclid(86_400);
    let (hour, minute, second) = (
        secs_of_day / 3_600,
        (secs_of_day % 3_600) / 60,
        secs_of_day % 60,
    );
    let (year, month, day) = civil_from_days(days);
    format!("{year:04}-{month:02}-{day:02}T{hour:02}:{minute:02}:{second:02}.{millis:03}Z")
}

/// Convert a count of days since the Unix epoch (1970-01-01) into a
/// `(year, month, day)` civil date — Howard Hinnant's `civil_from_days`
/// (<http://howardhinnant.github.io/date_algorithms.html>), valid across the full
/// proleptic Gregorian range.
fn civil_from_days(days: i64) -> (i64, u32, u32) {
    let z = days + 719_468;
    let era = if z >= 0 { z } else { z - 146_096 } / 146_097;
    let doe = z - era * 146_097; // [0, 146096]
    let yoe = (doe - doe / 1_460 + doe / 36_524 - doe / 146_096) / 365; // [0, 399]
    let year = yoe + era * 400;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100); // [0, 365]
    let mp = (5 * doy + 2) / 153; // [0, 11]
    let day = (doy - (153 * mp + 2) / 5 + 1) as u32; // [1, 31]
    let month = if mp < 10 { mp + 3 } else { mp - 9 } as u32; // [1, 12]
    let year = year + i64::from(month <= 2);
    (year, month, day)
}

